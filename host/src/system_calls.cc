const SystemCall *linuxSystemCall(uint64_t number) {
  const SystemCall *end = std::end(LINUX_X86_64);
  const SystemCall *found = std::lower_bound(std::begin(LINUX_X86_64), end, number,
                                             [](const SystemCall &call, uint64_t n) { return call.number < n; });
  return found != end && found->number == number ? found : nullptr;
}

