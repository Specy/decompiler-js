#!/usr/bin/env bash
# Vendors the subset of upstream Ghidra this package builds into ghidra/.
#
#   scripts/vendor-ghidra.sh <tag> [work directory]
#
# e.g. scripts/vendor-ghidra.sh Ghidra_12.1.4_build. The clone is shallow and
# sparse (only the paths below are fetched) and goes into the work directory,
# a new temporary directory when none is given. ghidra/ is then replaced
# wholesale, README.md included, so a vendored tree is always exactly what one
# tag gives. Moving to another release is a deliberate change: run this, then
# rebuild the specs and the wasm and commit everything together.
set -euo pipefail

tag="${1:?usage: scripts/vendor-ghidra.sh <tag> [work directory]}"
work="${2:-$(mktemp -d)}"
repo_dir="$(cd "$(dirname "$0")/.." && pwd)"
dest="$repo_dir/ghidra"
clone="$work/ghidra-$tag"
upstream=https://github.com/NationalSecurityAgency/ghidra.git

decompile_src=Ghidra/Features/Decompiler/src/decompile
# Per architecture: the upstream language directory, the processor description
# it is compiled from, and the specification files a SleighArchitecture reads
# beside the compiled .sla. Each .slaspec's @include files are found below.
architectures=(
    'x86 Ghidra/Processors/x86/data/languages x86-64.slaspec x86-64.pspec x86-64-gcc.cspec x86.ldefs'
)
# Upstream files in decompile/cpp that are documentation only.
cpp_excluded=(Doxyfile doccore.hh docmain.hh)

if [ -e "$clone" ]; then
    echo "$clone already exists; pass an empty work directory" >&2
    exit 1
fi
mkdir -p "$work"

sparse=(/LICENSE /NOTICE /licenses/zlib_License.txt "/$decompile_src/cpp/" "/$decompile_src/zlib/")
for entry in "${architectures[@]}"; do
    read -r _ languages _ <<<"$entry"
    sparse+=("/$languages/")
done

git -c advice.detachedHead=false clone --quiet --depth 1 --branch "$tag" --filter=blob:none --sparse "$upstream" "$clone"
git -C "$clone" sparse-checkout set --no-cone "${sparse[@]}"
commit="$(git -C "$clone" rev-parse HEAD)"

# Every file reached from a .slaspec through @include, the .slaspec included.
slaspec_closure() {
    local dir="$1" file="$2"
    local -A seen=()
    local queue=("$file")
    while [ "${#queue[@]}" -gt 0 ]; do
        local next="${queue[0]}"
        queue=("${queue[@]:1}")
        [ -n "${seen[$next]:-}" ] && continue
        seen[$next]=1
        echo "$next"
        while read -r included; do
            queue+=("$included")
        done < <(sed -n 's/^[[:space:]]*@include[[:space:]]*"\([^"]*\)".*/\1/p' "$dir/$next")
    done
}

rm -rf "$dest"
mkdir -p "$dest/decompile" "$dest/licenses"
cp "$clone/LICENSE" "$clone/NOTICE" "$dest/"
cp "$clone/licenses/zlib_License.txt" "$dest/licenses/"
cp -R "$clone/$decompile_src/cpp" "$dest/decompile/cpp"
cp -R "$clone/$decompile_src/zlib" "$dest/decompile/zlib"
for name in "${cpp_excluded[@]}"; do
    rm -f "$dest/decompile/cpp/$name"
done

language_rows=''
for entry in "${architectures[@]}"; do
    read -r processor languages slaspec spec_files <<<"$entry"
    to="$dest/processors/$processor/languages"
    mkdir -p "$to"
    files=($(slaspec_closure "$clone/$languages" "$slaspec") $spec_files)
    for name in "${files[@]}"; do
        cp "$clone/$languages/$name" "$to/$name"
    done
    language_rows+="| \`processors/$processor/languages/\` | \`$languages/\`, ${#files[@]} files: \`$slaspec\`, everything it includes, and the specification files read beside its \`.sla\`: $(printf '`%s`, ' $(printf '%s\n' "${files[@]}" | sort) | sed 's/, $//'). | Apache-2.0 |
"
done

cat >"$dest/README.md" <<EOF
# Vendored Ghidra

Generated by \`scripts/vendor-ghidra.sh $tag\`; do not edit by hand. Every file here is
upstream's, unchanged. Our changes are in \`../patches/\`, applied to a copy at build time.

- Upstream: $upstream
- Tag: \`$tag\`
- Commit: \`$commit\`

## Files taken

| Here | Upstream | Licence |
| --- | --- | --- |
| \`LICENSE\`, \`NOTICE\` | \`LICENSE\`, \`NOTICE\` (repository root) | |
| \`licenses/zlib_License.txt\` | \`licenses/zlib_License.txt\` | |
| \`decompile/cpp/\` | \`$decompile_src/cpp/\`, without the documentation files $(printf '`%s`, ' "${cpp_excluded[@]}" | sed 's/, $//') | Apache-2.0 |
| \`decompile/zlib/\` | \`$decompile_src/zlib/\` (a subset of zlib 1.3.1) | zlib License |
$language_rows
## Licences

Ghidra is released under the Apache License, Version 2.0 (\`LICENSE\`), with the notice in
\`NOTICE\`. The zlib sources in \`decompile/zlib/\` are under the zlib License
(\`licenses/zlib_License.txt\`, also at the top of \`decompile/zlib/zlib.h\`); the decompiler
uses them to read compressed \`.sla\` files.
EOF

echo "Vendored $tag ($commit) into $dest"
